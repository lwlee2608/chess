const PHASE_WEIGHT: Record<PieceType, number> = { pawn: 0, knight: 1, bishop: 1, rook: 2, queen: 4, king: 0 }
const OPENING_PHASE = 24

const TABLES: Record<PieceType, readonly number[]> = {
  pawn: PAWN_TABLE,
  knight: KNIGHT_TABLE,
  bishop: BISHOP_TABLE,
  rook: ROOK_TABLE,
  queen: QUEEN_TABLE,
  king: KING_TABLE,
}

export function evaluate(position: Position, perspective: Color): number {
  let score = 0
  let phase = 0
  let kingScore = 0
  for (let square = 0; square < 64; square += 1) {
    const piece = position.board[square]
    if (!piece) continue
    const sign = piece.color === perspective ? 1 : -1
    const tableSquare = piece.color === 'white' ? square : 63 - square
    score += sign * (MATERIAL[piece.type] + TABLES[piece.type][tableSquare])
    phase += PHASE_WEIGHT[piece.type]
    if (piece.type === 'king') kingScore += sign * (KING_ENDGAME_TABLE[tableSquare] - KING_TABLE[tableSquare])
  }
  const endgameWeight = 1 - Math.min(phase, OPENING_PHASE) / OPENING_PHASE
  return score + Math.round(kingScore * endgameWeight)
}
